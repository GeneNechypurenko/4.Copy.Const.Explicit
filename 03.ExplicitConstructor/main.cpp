#include <iostream>
#include <cstring>
#include <windows.h>

using namespace std;

/*
==========================================================================================================================================
                                                Конструктор з ключовим словом explicit
==========================================================================================================================================

  У C++ ключеве слово explicit використовується для заборони неявного приведення типів та неявного копіювального ініціалізування
  при створенні об'єктів. Його головна практична мета — запобігти прихованим логічним помилкам, які можуть виникнути, коли компилятор
  непомітно для розробника трансформує один тип даних в інший.

  Якщо ви використовуєте конструктор з одним параметром без ключового слова explicit - для компілятора він стає конструктором перетворення.

  Конструктор перетворення (або converting constructor) — це такий конструктор у C++, який компілятор може використовувати
  для автоматичного (неявного) перетворення значення одного типу на об'єкт вашого класу.

  Правила використання explicit в сучасному C++:
  1. Завжди робіть конструктори, які можуть приймати один аргумент, оголошеними як explicit.
  2. Виключайте explicit лише тоді, коли неявне перетворення є частиною дизайну вашого класу, наприклад:
  створення об'єкта MyString із класичного рядка const char* - тут перетворення має відбуватись.
  3. Конструктор копіювання explicit НЕ роблять: інакше перестануть працювати  Student b = a; і передача об'єкта за значенням.

  Де відбувається неявне створення об'єкта
     1) ініціалізація через = : Student s = "Олег";
     2) передача аргументу у функцію: printCard("Анна"); (параметр типу Student або const Student&)
     3) повернення з функції: return "Тарас";  тип Student У випадках 2) і 3) створюється ТИМЧАСОВИЙ об'єкт: конструктор
     і деструктор викликаються, хоча в коді об'єкта не видно.

  Чим це небезпечно
     - код вводить в оману: printCard("Анна") схоже на роботу з рядком;
     - компілятор не помічає помилок типів: IntArray arr = 10; - буде масивом із 10 нулів, а не масив зі значенням 10
     - зайві тимчасові об'єкти: new / delete[] там, де їх ніхто не просив.
*/

class Student
{
private:
    char* name;
    int age;

public:
    Student(const char* name, int age) : name(nullptr), age(age)
    {
        setName(name);
        cout << "  [+] Створено: " << this->name << endl;
    }

    // Конструктор перетворення (один параметр) — делегує основному.
    // Демонстрація: приберіть explicit і розкоментуйте рядки в пункті 2 main.
    explicit Student(const char* name) : Student(name, 16)
    {}

    Student(const Student& other) : name(nullptr), age(other.getAge())
    {
        setName(other.getName());
        cout << "  [=] Копія: " << name << endl;
    }

    ~Student()
    {
        cout << "  [-] Знищено: " << name << endl;
        delete[] name;
    }

    void setName(const char* name)
    {
        delete[] this->name;
        int length = strlen(name) + 1;
        this->name = new char[length];
        strcpy_s(this->name, length, name);
    }

    const char* getName() const
    {
        return name;
    }

    int getAge() const
    {
        return age;
    }

    void print() const
    {
        cout << "  " << name << ", вік: " << age << endl;
    }
};

void printCard(const Student& s)
{
    cout << "  Картка студента:" << endl;
    s.print();
}

int main()
{
    SetConsoleOutputCP(65001);
    SetConsoleCP(65001);

    cout << "1. Явне створення — працює завжди" << endl;
    Student a("Олена");
    Student b{ "Ігор" };
    printCard(a);
    printCard(Student("Марія"));    // явний тимчасовий об'єкт: [+] ... [-] одразу після виклику

    cout << "2. Неявне створення — заборонено explicit" << endl;
    // Без explicit кожен рядок компілюється і створює об'єкт Student, хоча слово Student у рядку не написано:
    // Student c = "Олег";          // const char* → Student
    // printCard("Анна");           // тимчасовий Student: [+] Анна ... [-] Анна
    // Student d = { "Петро" };     // ініціалізація списком через = теж неявна

    cout << "3. Конструктор із двома параметрами explicit не має" << endl;
    Student e = { "Ірина", 19 };    // дозволено: конструктор не explicit
    e.print();

    cout << "Кінець main" << endl;
    return 0;
}

/*
  ІНСАЙТИ / BEST PRACTICES
  - Конструктором перетворення вважається будь-який конструктор, оголошений без ключового слова explicit, який можна викликати
  з одним аргументом.
  - Найнебезпечніший випадок без explicit: printCard(0);
    *   Компілюється!
    *   0 перетворюється на нульовий покажчик const char*,
    *   з нього неявно створюється Student,
    *   а потім strlen(nullptr) аварійно завершує програму! І ви не знаєте в чому проблема, в дебаг моді програма "лягає" на цій строчці,
    але по лозіці все має працювати як треба!
    *   З explicit просто помилка компіляції (компілятор не дозволить передати 0 в аргументи).
  - Ще одна пастка без explicit:  b = "Олег";
    *   створює тимчасовий Student і ПРИСВОЮЄ його b.
    *   Стандартний оператор присвоєння копіює лише адресу name → подвійний delete[] → аварійне завершення.
  - Тимчасові об'єкти видно у виводі [+] / [-]: якщо бачите створення об'єкта, якого немає в коді, — шукайте неявне перетворення.
  - Звичка професіоналів: кожен конструктор з одним параметром одразу explicit. Прибрати explicit — свідоме рішення, коли перетворення
    природне
  - Починаючи із стандарта C++11 (2011 рік) explicit діє і на конструктори з кількома параметрами — в такому випадку:
    *   забороняється виклик Student e = { "Ірина", 19 };
    *   дозволено тільки Student e{ "Ірина", 19 };
*/
