using namespace std;

/*
==========================================================================================================================================
                                                           Конструктор копіювання
==========================================================================================================================================

  
  Конструктор копіювання (Copy Constructor) у C++ - це спеціальний конструктор, який викликається для створення нового об'єкта як копії
  вже існуючого об'єкта того самого класу.

  Конструктор копіювання викликається у трьох випадках:
     1. Явна ініціалізація одного об'єкта іншим при створенні:
        Student b = a;
        Student b(a);
        Student b{ a };
     2. Передача об'єкта у функцію ЗА ЗНАЧЕННЯМ:
        void show(Student s);
     3. Повернення об'єкта з функції ЗА ЗНАЧЕННЯМ:
        Student older(Student& first, Student& second){...}

  Якщо не створити власний конструктор копіювання, компілятор створить дефолтний конструктор копіювання.
  Конструктор копіювання створений компілятором просто копіює всі поля посимвольно (поверхневе копіювання / shallow copy).
  
  Поверхневе копіювання (Shallow Copy): Добре працює для простих типів (bool, char, int, double) та string. Але якщо клас містить
  вказівники на динамічну пам'ять (виділену через new), дефолтний конструктор просто скопіює адресу вказівника. У результаті два об'єкти
  будуть вказувати на одну й ту саму ділянку пам'яті. Це призведе до помилки при видаленні об'єктів.
  В такому випадку виникає необхідність створити власний конструктор копіювання: скопіювати ВСІ поля — відповідальність програміста.

*/

class Student
{
private:
    char* name;
    int age;

public:
    Student(const char* name, int age) : name(nullptr), age(age)
    {
        setName(name);
        cout << "  [+] Конструктор: " << this->name << endl;
    }

    // ===== КОНСТРУКТОР КОПІЮВАННЯ =====
    Student(const Student& other) : name(nullptr), age(other.age)
    {
        setName(other.name);   // НОВА пам'ять + копія рядка (other.name — private, але доступний)
        cout << "  [=] Копіювання: " << name << endl;
    }

    ~Student()
    {
        cout << "  [-] Деструктор: " << name << endl;
        delete[] name;
    }

    void setName(const char* name)
    {
        delete[] this->name;
        size_t length = strlen(name) + 1;
        this->name = new char[length];
        strcpy_s(this->name, length, name);
    }

    int getAge()
    {
        return age;
    }

    void print()
    {
        // (void*) — щоб cout вивів адресу, а не рядок
        cout << "  " << name << ", вік: " << age << "  (адреса name: " << &name << ")" << endl;
    }
};

// Передача за значенням: s — копія аргументу
void showByValue(Student s)
{
    s.print();
}   // тут знищується копія s

// Повернення за значенням: повертається копія одного з параметрів
Student older(Student& first, Student& second)
{
    if (first.getAge() >= second.getAge())
    {
        return first;
    }
    return second;
}

int main()
{
    SetConsoleOutputCP(65001);
    SetConsoleCP(65001);

    Student a("Олена", 20);

    cout << "1. Ініціалізація іншим об'єктом" << endl;
    Student b = a;
    a.print();
    b.print();              // з конструктором копіювання адреси name РІЗНІ
    b.setName("Олена Копія");
    a.print();              // оригінал не змінився
    b.print();

    cout << "2. Передача у функцію за значенням" << endl;
    showByValue(a);         // створюється і знищується копія
    a.print();              // a цілий і неушкоджений

    cout << "3. Повернення з функції за значенням" << endl;
    Student c("Ігор", 22);
    Student d = older(a, c);
    d.print();

    return 0;
}

/*
  ІНСАЙТИ / BEST PRACTICES
  - Компілятор забороняє передавати об'єкт в параметр конструктора за значенням і це зроблено навмисно. Причина криється в тому що:
    якщо б було дозволено передавати параметр за значенням, то для самої передачі параметра знову знадобиться копіювання, що призведе
    до нескінченної рекурсії.
  - Ознака, що класу потрібен власний конструктор копіювання - у класі є деструктор, який звільняє пам'ять (delete / delete[]).
  - Найпідступніший випадок — передача об'єкта за значенням у функцію:
    Функція на виході знищує копію і звільняє пам'ять оригіналу, спочатку ви нічого не помітити, все відпрацює. Помилка проявиться
    пізніше, в зовсім іншому місці програми.
  - Копіювання — дорога операція, щоб уникнути зайвих копій, передавайте об'єкти у функції за посиланням: Student&.
  - Якщо в класі є статичний лічильник об'єктів, стандартний конструктор копіювання його НЕ збільшить, а деструктор копії — зменшить.
  - Не пишіть конструктор копіювання «про всяк випадок» - для класів без динамічної пам'яті стандартний працює правильно.

  ==========================================================================================================================================

  ПРАКТИКА

  1. Додайте в Student поле group (char*, наприклад "ПВ-251"):
     - метод setGroup — як setName;
     - конструктор приймає group третім параметром;
     - не забудьте про деструктор і конструктор копіювання.
     Перевірте, що копія має власну адресу group.

  1. Клас IntArray:
     - поля: int* data, int size;
     - конструктор IntArray(int size) — виділяє new int[size] і заповнює нулями;
     - деструктор — delete[] data;
     - методи set(int index, int value), get(int index), print();
     - конструктор копіювання IntArray(const IntArray& other):
       виділити new int[other.size] і циклом скопіювати всі елементи.
     У main:
        створіть масив,
        заповніть його,
        скопіюйте (IntArray copy = arr;),
        змініть один елемент копії і виведіть обидва масиви.

*/
