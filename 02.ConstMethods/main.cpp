#include <iostream>
#include <cstring>
#include <windows.h>

using namespace std;

/*
==========================================================================================================================================
                                                            Константні методи
==========================================================================================================================================

  Константні методи в C++ використовуються для того, щоб гарантувати компілятору та іншим програмістам: цей метод не змінює стан об'єкта.

  Основні причини використання константних методів:
  1. Якщо ви створите константний об'єкт класу, ви зможете викликати для нього тільки константні методи.
  2. Контроль коду: компілятор не дасть випадково змінити об'єкт, а читач класу одразу бачить, які методи безпечні.

  В константних методах this завжди має тип const Ім'яКласу*. Тому статичні методи константними не бувають - у статичного методу немає this.

  Головне правило: кожен метод, який не змінює поля (гетери, print, обчислення), оголошуйте константним — одразу.

  Ключове слово mutable — поле, яке можна змінювати навіть у константному методі. Використовується лише для СЛУЖБОВИХ полів, які не
  є даними об'єкта: лічильник звернень, статистика.
*/

class Student
{
private:
    char* name;
    int age;
    mutable int views;          // скільки разів профіль виводили на екран

public:
    Student(const char* name, int age) : name(nullptr), age(age), views(0)
    {
        setName(name);
    }

    // Конструктор копіювання: other — const Student&, тому тут можна викликати ЛИШЕ константні методи.
    // Демонстрація: приберіть const у getAge() — цей рядок перестане компілюватися.
    // views НЕ копіюємо: це новий профіль, його ще ніхто не переглядав.
    Student(const Student& other) : name(nullptr), age(other.getAge()), views(0)
    {
        setName(other.getName());
    }

    ~Student()
    {
        delete[] name;
    }

    // ----- Модифікатори: змінюють поля, тому НЕ константні -----
    void setName(const char* name)
    {
        delete[] this->name;
        int length = strlen(name) + 1;
        this->name = new char[length];
        strcpy_s(this->name, length, name);
    }

    void setAge(int age)
    {
        if (age > 0)
        {
            this->age = age;
        }
    }

    // ----- Інспектори: лише читають поля, тому константні -----
    const char* getName() const
    {
        return name;            // const char* — ззовні рядок змінити не можна
    }

    int getAge() const
    {
        return age;
    }

    int getViews() const
    {
        return views;
    }

    bool isAdult() const
    {
        // age = 18;            // ПОМИЛКА C3490: this — const Student*, поля змінювати не можна
        // setAge(18);          // ПОМИЛКА C2662: setAge не константний
        return getAge() >= 18;  // OK: getAge константний
    }

    void print() const;         // тіло — за межами класу
};

// const повторюється і в оголошенні, і у визначенні
void Student::print() const
{
    views++;                    // OK: views — mutable, змінюється навіть у константному методі
    // age++;                   // ПОМИЛКА C3490: звичайне поле змінювати не можна

    cout << "  " << name << ", вік: " << age;
    if (isAdult())
    {
        cout << " (повнолітній)";
    }
    cout << endl;
}

int main()
{
    SetConsoleOutputCP(65001);
    SetConsoleCP(65001);

    cout << "1. Звичайний об'єкт: доступні всі методи" << endl;
    Student a("Олена", 17);
    a.setAge(18);
    a.print();

    cout << "2. Константний об'єкт: лише константні методи" << endl;
    const Student boss("Анна", 40);
    boss.print();
    cout << "  Ім'я: " << boss.getName() << endl;
    // boss.setAge(41);         // ПОМИЛКА C2662: setAge не константний

    cout << "3. mutable: лічильник змінюється навіть у константного об'єкта" << endl;
    boss.print();
    boss.print();
    cout << "  Профіль " << boss.getName() << " переглянули " << boss.getViews() << " раз(и)" << endl;
    cout << "  Профіль " << a.getName() << " переглянули " << a.getViews() << " раз(и)" << endl;

    return 0;
}

/*
  ІНСАЙТИ / BEST PRACTICES
  - const у методі — частина інтерфейсу класу: читач одразу бачить, які методи безпечні і нічого не змінюють.
  - Ключове слово mutable — використовується дуже рідко, лише для «службових» полів, що не входять у стан об'єкта
    (наприклад, лічильник звернень до об'єкта).
  - Перевірка, чи підходить поле для mutable: «Якщо це поле зміниться, чи стане об'єкт ІНШИМ?»
    Змінився вік — це вже інший стан студента, mutable не можна.
    Змінився лічильник переглядів — студент той самий, mutable доречний.
  - Не використовуйте mutable, щоб «обійти» помилку компілятора.
    Якщо метод змінює дані об'єкта, правильне рішення — прибрати const з методу, а не додати mutable до поля.

  ПРАКТИКА
  1. Клас Product (товар в інтернет-магазині):
     - поля: char* name, double price, mutable int views;
     - конструктор Product(const char* name, double price) — views = 0;
     - конструктор копіювання (views НЕ копіюється, як у Student) і деструктор;
     - setPrice — приймає лише значення > 0 (як setAge у Student);
     - getName, getPrice, getViews — константні;
     - print() const — збільшує views і виводить «Назва: ціна грн».
     У main: створіть const Product, викличте print тричі і виведіть getViews().
     Спробуйте викликати setPrice у константного товару, прочитайте помилку і закоментуйте рядок.

  2. Клас Rectangle з «кешем» площі (mutable для збереження результату обчислення):
     - поля: double width, double height, mutable double cachedArea, mutable bool areaReady;
     - конструктор: areaReady = false;
     - getArea() const:
         * якщо areaReady == false — вивести «(обчислюю площу)», записати width * height у cachedArea, areaReady = true;
         * повернути cachedArea;
     - setWidth, setHeight — приймають лише значення > 0 і ставлять areaReady = false (стара площа більше не правильна).
     У main: викличте getArea двічі поспіль — повідомлення «(обчислюю площу)» має з'явитися лише один раз.
     Потім змініть ширину і знову викличте getArea — площа має обчислитися заново.

  3. Усно: для кожного поля скажіть, чи доречний mutable, і чому (тест: «чи стане об'єкт ІНШИМ?»):
     - balance у класі банківського рахунку;
     - лічильник того, скільки разів викликали getBalance();
     - name у класі Student;
     - cachedArea у Rectangle з завдання 2;
     - score у класі гравця.
*/
